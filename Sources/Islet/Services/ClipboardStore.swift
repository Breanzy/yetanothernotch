import AppKit
import ImageIO

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, link, image, file }

    var id = UUID()
    var kind: Kind
    var text: String?
    var filePaths: [String]?
    /// For images: file name inside the clipboard image folder, plus size info for the list.
    var imageFile: String?
    var imageWidth: Int?
    var imageHeight: Int?
    var imageBytes: Int?
    var sourceBundleID: String?
    var date = Date()
    var pinned = false

    var title: String {
        switch kind {
        case .text: "Text"
        case .link: "Link"
        case .image: "Image"
        case .file: (filePaths?.count ?? 0) > 1 ? "\(filePaths!.count) Files" : "File"
        }
    }

    var fileURLs: [URL] { (filePaths ?? []).map { URL(fileURLWithPath: $0) } }

    /// One-line label for the list, e.g. "Image: 439×281 (1.9 MB)".
    var listTitle: String {
        switch kind {
        case .text:
            // Only the start matters for a one-line title (texts can be 50k characters).
            let line = (text ?? "").prefix(400).split(whereSeparator: \.isNewline)
                .first(where: { !$0.trimmingCharacters(in: .whitespaces).isEmpty }) ?? ""
            return line.trimmingCharacters(in: .whitespaces)
                .replacingOccurrences(of: "\t", with: " ")
        case .link:
            return text ?? ""
        case .image:
            guard let w = imageWidth, let h = imageHeight else { return "Image" }
            let size = imageBytes.map { " (" + ByteCountFormatter.string(fromByteCount: Int64($0), countStyle: .file) + ")" } ?? ""
            return "Image: \(w)×\(h)\(size)"
        case .file:
            return fileURLs.map(\.lastPathComponent).joined(separator: ", ")
        }
    }

    func matches(_ query: String) -> Bool {
        guard !query.isEmpty else { return true }
        let haystack = (text ?? "") + " " + (filePaths ?? []).map { ($0 as NSString).lastPathComponent }.joined(separator: " ")
        return haystack.localizedCaseInsensitiveContains(query)
    }

    /// Same content, ignoring id/date/pin.
    func sameContent(as other: ClipItem) -> Bool {
        kind == other.kind && text == other.text && filePaths == other.filePaths
    }
}

/// Watches the general pasteboard and keeps a history of what you copy.
///
/// History is saved to disk (readable only by you) so it survives a restart. Images are stored
/// as files and only small thumbnails are ever kept in memory, and only while the panel is open.
/// Anything a password manager marks as concealed or transient is never recorded.
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = [] {
        didSet { filteredCache = nil }
    }
    /// Search text and keyboard selection for the clipboard tab.
    @Published var query = "" {
        didSet { if query != oldValue { selectedID = nil; filteredCache = nil } }
    }
    @Published var selectedID: UUID?
    /// Set only by keyboard navigation, so the list scrolls for arrow keys but never under the pointer.
    @Published private(set) var scrollTarget: UUID?
    private var filteredCache: [ClipItem]?
    /// Briefly set after copying so the row can flash "Copied".
    @Published private(set) var lastCopiedID: UUID?
    private var keyMonitor: Any?

    static let maxItems = 60
    private static let maxStoredTextLength = 50_000
    private static let maxImageBytes = 15 * 1024 * 1024

    /// Pasteboard markers used by password managers and similar apps (nspasteboard.org).
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Small thumbnails, created on demand and purged when the notch closes.
    private let thumbnails: NSCache<NSUUID, NSImage> = {
        let c = NSCache<NSUUID, NSImage>()
        c.countLimit = 24
        return c
    }()
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    private let fileURL: URL = {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Islet", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true,
                                                 attributes: [.posixPermissions: 0o700])
        return dir.appendingPathComponent("clipboard.json")
    }()

    private let imagesDir: URL = {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Islet/ClipImages", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true,
                                                 attributes: [.posixPermissions: 0o700])
        return dir
    }()

    private func imageURL(_ item: ClipItem) -> URL? {
        item.imageFile.map { imagesDir.appendingPathComponent($0) }
    }

    init() {
        UserDefaults.standard.removeObject(forKey: "clipboard.recording") // old pause setting, replaced by the Layout switch
    }

    /// Recording follows the Clipboard switch in Settings → Layout. While off, nothing is
    /// recorded, the pasteboard isn't checked, and history is unloaded from memory (it stays
    /// on disk and comes back when you switch it on again).
    private(set) var isActive = false

    func setActive(_ active: Bool) {
        guard active != isActive else { return }
        isActive = active
        if active {
            load()
            // Start from what's on the clipboard now; things copied while off aren't recorded.
            lastChangeCount = NSPasteboard.general.changeCount
            let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.check() }
            }
            t.tolerance = 0.1 // lets macOS batch the wake-ups with other work
            RunLoop.main.add(t, forMode: .common)
            timer = t
        } else {
            timer?.invalidate()
            timer = nil
            stopKeyHandling()
            query = ""
            selectedID = nil
            items = [] // already saved; only memory is cleared
            purgeThumbnails()
        }
    }

    /// Decodes only a small thumbnail straight from the file (never the full image).
    func thumbnail(for item: ClipItem) -> NSImage? {
        if let cached = thumbnails.object(forKey: item.id as NSUUID) { return cached }
        guard let url = imageURL(item),
              let source = CGImageSourceCreateWithURL(url as CFURL, nil),
              let cg = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                  kCGImageSourceCreateThumbnailFromImageAlways: true,
                  kCGImageSourceCreateThumbnailWithTransform: true,
                  kCGImageSourceThumbnailMaxPixelSize: 280,
              ] as CFDictionary) else { return nil }
        let image = NSImage(cgImage: cg, size: NSSize(width: cg.width / 2, height: cg.height / 2))
        thumbnails.setObject(image, forKey: item.id as NSUUID)
        return image
    }

    /// Larger image for the preview pane, if it's already decoded.
    func cachedPreview(for item: ClipItem) -> NSImage? {
        previews.object(forKey: item.id as NSUUID)
    }

    /// Decodes the preview image off the main thread, so hovering over images never stutters.
    func loadPreview(for item: ClipItem) async -> NSImage? {
        if let cached = cachedPreview(for: item) { return cached }
        guard let url = imageURL(item) else { return nil }
        let decoded = await Task.detached(priority: .userInitiated) { () -> CGImageBox? in
            guard let source = CGImageSourceCreateWithURL(url as CFURL, nil),
                  let cg = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                      kCGImageSourceCreateThumbnailFromImageAlways: true,
                      kCGImageSourceCreateThumbnailWithTransform: true,
                      kCGImageSourceThumbnailMaxPixelSize: 900,
                  ] as CFDictionary) else { return nil }
            return CGImageBox(image: cg)
        }.value
        guard let cg = decoded?.image else { return nil }
        let image = NSImage(cgImage: cg, size: NSSize(width: cg.width / 2, height: cg.height / 2))
        previews.setObject(image, forKey: item.id as NSUUID)
        return image
    }

    private let previews: NSCache<NSUUID, NSImage> = {
        let c = NSCache<NSUUID, NSImage>()
        c.countLimit = 3
        return c
    }()

    func purgeThumbnails() {
        thumbnails.removeAllObjects()
        previews.removeAllObjects()
    }

    // MARK: - List, selection & keyboard

    /// Search results: pinned first, then newest first.
    /// Cached; rebuilt only when the items or the search change (not on every hover).
    var filteredItems: [ClipItem] {
        if let cached = filteredCache { return cached }
        let list = items.filter { $0.matches(query) }
            .enumerated()
            .sorted { ($0.element.pinned ? 0 : 1, $0.offset) < ($1.element.pinned ? 0 : 1, $1.offset) }
            .map(\.element)
        filteredCache = list
        return list
    }

    /// Pointer hover selects a row (no-op when it's already selected, so mouse moves are free).
    func hover(_ id: UUID) {
        if selectedID != id { selectedID = id }
    }

    var selectedItem: ClipItem? {
        let list = filteredItems
        return list.first { $0.id == selectedID } ?? list.first
    }

    func moveSelection(by delta: Int) {
        let list = filteredItems
        guard !list.isEmpty else { return }
        let current = list.firstIndex { $0.id == selectedItem?.id } ?? 0
        let id = list[min(max(0, current + delta), list.count - 1)].id
        selectedID = id
        scrollTarget = id
    }

    /// ↑/↓ move, ↩ copies, ⌘1–⌘9 copy that row, ⌘⌫ deletes, Esc clears the search.
    func startKeyHandling() {
        guard keyMonitor == nil else { return }
        keyMonitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] event in
            let handled = MainActor.assumeIsolated { self?.handleKey(event) ?? false }
            return handled ? nil : event
        }
    }

    func stopKeyHandling() {
        if let m = keyMonitor { NSEvent.removeMonitor(m) }
        keyMonitor = nil
    }

    private func handleKey(_ event: NSEvent) -> Bool {
        let cmd = event.modifierFlags.contains(.command)
        if cmd, let ch = event.charactersIgnoringModifiers, let n = Int(ch), (1...9).contains(n) {
            let list = filteredItems
            if n <= list.count { selectedID = list[n - 1].id; copy(list[n - 1]) }
            return true
        }
        switch event.keyCode {
        case 125: moveSelection(by: 1); return true            // ↓
        case 126: moveSelection(by: -1); return true           // ↑
        case 36, 76:                                           // ↩ / enter
            if let item = selectedItem { copy(item) }
            return true
        case 51 where cmd:                                     // ⌘⌫
            if let item = selectedItem {
                moveSelection(by: 1)
                if selectedID == item.id { moveSelection(by: -1) }
                delete(item)
            }
            return true
        case 53:                                               // esc
            guard !query.isEmpty else { return false }
            query = ""
            return true
        default:
            return false
        }
    }

    // MARK: - Capture

    private func check() {
        guard isActive else { return }
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount

        let types = pb.types ?? []
        if types.contains(where: { Self.privateTypes.contains($0.rawValue) }) { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        // 1. Files (Finder copies)
        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            insert(ClipItem(kind: .file, filePaths: urls.map(\.path), sourceBundleID: source))
            return
        }
        // 2. Text / links. Only the stored part is examined, so copying a huge log or file
        // doesn't stall the app scanning megabytes of text.
        if let full = pb.string(forType: .string) {
            let string = String(full.prefix(Self.maxStoredTextLength))
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return }
            let isLink = trimmed.count < 2048 && !trimmed.contains(where: \.isWhitespace)
                && (URL(string: trimmed)?.scheme.map { ["http", "https", "mailto", "ftp"].contains($0) } ?? false)
            insert(ClipItem(kind: isLink ? .link : .text, text: string, sourceBundleID: source))
            return
        }
        // 3. Images. Encoding and writing happen in the background. TIFF (what most apps copy)
        // is uncompressed and huge, so it's stored as PNG — a fraction of the disk space.
        for type in [NSPasteboard.PasteboardType.png, .tiff] where types.contains(type) {
            let limit = type == .tiff ? Self.maxImageBytes * 4 : Self.maxImageBytes
            guard let data = pb.data(forType: type), data.count <= limit else { continue }
            var item = ClipItem(kind: .image, sourceBundleID: source)
            let name = "\(item.id.uuidString).png"
            item.imageFile = name
            let url = imagesDir.appendingPathComponent(name)
            let isTIFF = type == .tiff
            let maxBytes = Self.maxImageBytes
            Self.imageQueue.async { [weak self] in
                let png = isTIFF ? Self.pngData(fromTIFF: data) : data
                guard let png, png.count <= maxBytes,
                      (try? png.write(to: url, options: .atomic)) != nil else { return }
                try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
                var width: Int?, height: Int?
                if let src = CGImageSourceCreateWithData(png as CFData, nil),
                   let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any] {
                    width = props[kCGImagePropertyPixelWidth] as? Int
                    height = props[kCGImagePropertyPixelHeight] as? Int
                }
                let bytes = png.count
                DispatchQueue.main.async {
                    MainActor.assumeIsolated {
                        guard let self else { return }
                        // Recording was switched off while the image was being saved.
                        guard self.isActive else { try? FileManager.default.removeItem(at: url); return }
                        item.imageBytes = bytes
                        item.imageWidth = width
                        item.imageHeight = height
                        self.insert(item)
                    }
                }
            }
            return
        }
    }

    private static let imageQueue = DispatchQueue(label: "app.islet.clipboard.images", qos: .utility)
    private static let saveQueue = DispatchQueue(label: "app.islet.clipboard.save", qos: .utility)

    nonisolated static func pngData(fromTIFF data: Data) -> Data? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let out = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(out, "public.png" as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImageFromSource(dest, source, 0, nil)
        return CGImageDestinationFinalize(dest) ? out as Data : nil
    }

    private func insert(_ item: ClipItem) {
        // Re-copying something already in the list moves it to the top instead of duplicating it.
        if item.kind != .image, let i = items.firstIndex(where: { $0.sameContent(as: item) }) {
            var existing = items.remove(at: i)
            existing.date = Date()
            items.insert(existing, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        trim()
        save()
    }

    private func trim() {
        while items.count > Self.maxItems, let i = items.lastIndex(where: { !$0.pinned }) {
            removeImageFile(items[i])
            items.remove(at: i)
        }
    }

    private func removeImageFile(_ item: ClipItem) {
        thumbnails.removeObject(forKey: item.id as NSUUID)
        if let url = imageURL(item) { try? FileManager.default.removeItem(at: url) }
    }

    // MARK: - Actions

    /// Puts an item back on the clipboard (and moves it to the top).
    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text, .link:
            pb.setString(item.text ?? "", forType: .string)
        case .file:
            pb.writeObjects(item.fileURLs as [NSURL])
        case .image:
            if let url = imageURL(item), let data = try? Data(contentsOf: url) {
                pb.setData(data, forType: url.pathExtension == "png" ? .png : .tiff)
            }
        }
        lastChangeCount = pb.changeCount // don't record our own write
        lastCopiedID = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.lastCopiedID == item.id { self?.lastCopiedID = nil }
        }
        if let i = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: i)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        save()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        removeImageFile(item)
        save()
    }

    /// Clears everything except pinned items.
    func clearUnpinned() {
        for item in items where !item.pinned { removeImageFile(item) }
        items.removeAll { !$0.pinned }
        save()
    }

    /// Removes unpinned items last copied more than `days` days ago. Returns how many were removed.
    @discardableResult
    func purge(olderThanDays days: Int, now: Date = Date()) -> Int {
        guard isActive, days > 0 else { return 0 }
        let cutoff = now.addingTimeInterval(-Double(days) * 86_400)
        let expired = items.filter { !$0.pinned && $0.date < cutoff }
        guard !expired.isEmpty else { return 0 }
        expired.forEach(removeImageFile)
        let ids = Set(expired.map(\.id))
        items.removeAll { ids.contains($0.id) }
        save()
        return expired.count
    }

    /// Drag provider so clips can be dragged straight into other apps.
    func itemProvider(for item: ClipItem) -> NSItemProvider {
        switch item.kind {
        case .text, .link:
            return NSItemProvider(object: (item.text ?? "") as NSString)
        case .file:
            return item.fileURLs.first.flatMap { NSItemProvider(contentsOf: $0) } ?? NSItemProvider()
        case .image:
            return imageURL(item).flatMap { NSItemProvider(contentsOf: $0) } ?? NSItemProvider()
        }
    }

    // MARK: - Persistence

    /// History can be a few MB of text, so encoding and writing happen off the main thread
    /// (in order, on a serial queue) instead of stalling the UI on every copy.
    private func save() {
        // While off, history isn't in memory; writing would wipe the saved copy.
        guard isActive else { return }
        let snapshot = items
        let url = fileURL
        Self.saveQueue.async {
            guard let data = try? JSONEncoder().encode(snapshot) else { return }
            try? data.write(to: url, options: .atomic)
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
        }
    }

    private func load() {
        guard let data = try? Data(contentsOf: fileURL),
              let saved = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        // Drop image entries whose file has gone missing.
        items = saved.filter { item in
            item.kind != .image || imageURL(item).map { FileManager.default.fileExists(atPath: $0.path) } == true
        }
    }

    // MARK: - Preview data (snapshot mode only)

    func loadPreviewItems() {
        items = [
            ClipItem(kind: .text, text: "Meeting moved to 3:30 — bring the Q4 numbers and the updated roadmap draft.",
                     sourceBundleID: "com.apple.MobileSMS", date: Date().addingTimeInterval(-40)),
            ClipItem(kind: .link, text: "https://developer.apple.com/documentation/swiftui",
                     sourceBundleID: "com.apple.Safari", date: Date().addingTimeInterval(-300), pinned: true),
            ClipItem(kind: .file, filePaths: ["/Applications/Safari.app"],
                     sourceBundleID: "com.apple.finder", date: Date().addingTimeInterval(-1800)),
            ClipItem(kind: .text, text: "let total = items.reduce(0) { $0 + $1.price }",
                     sourceBundleID: "com.apple.dt.Xcode", date: Date().addingTimeInterval(-7200)),
            ClipItem(kind: .text, text: "hello@example.com",
                     sourceBundleID: "com.apple.mail", date: Date().addingTimeInterval(-90000)),
            ClipItem(kind: .image, imageWidth: 439, imageHeight: 281, imageBytes: 1_900_000,
                     sourceBundleID: "com.google.Chrome", date: Date().addingTimeInterval(-100000)),
            ClipItem(kind: .text, text: "defaults write com.apple.dock autohide-delay -float 0",
                     sourceBundleID: "com.apple.Terminal", date: Date().addingTimeInterval(-200000)),
        ]
    }
}

/// Carries a decoded image back from the background decoder.
struct CGImageBox: @unchecked Sendable {
    let image: CGImage
}
